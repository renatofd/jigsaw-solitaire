type ThemeId = 'paisagens' | 'animais' | 'cidades' | 'flores' | 'comidas' | 'fantasia' | 'anime';

/** Builds `{ 'paisagens-01': ..., ... }` from 10 titles per theme, in level order. */
function titles(src: Record<ThemeId, string[]>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const theme of Object.keys(src) as ThemeId[]) {
    src[theme].forEach((title, i) => {
      out[`${theme}-${i + 1 < 10 ? '0' : ''}${i + 1}`] = title;
    });
  }
  return out;
}

